#include "ft_printf.h"

int	ft_print_str(char *str)
{
	int	i;

	i = 0;
	if (!str)
	{
		write(1, "(null)", 6);
		return (6);
	}
	while (str[i])
		i++;
	if (ft_putstr_fd_int(str, 1) == -1)
		return (-1);
	return (ft_strlen(str));
}
